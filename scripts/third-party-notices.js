'use strict';

// Writes public/third-party-notices.txt: the name, version, licence and licence text of every
// open-source package Rift ships or bundles. Run `npm run notices` after changing dependencies.
// (Most open-source licences require their notice to be kept with copies of the software.)

const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const lock = require(path.join(root, 'package-lock.json')).packages;
// Packages that are only used to build public/dashboard.js but are bundled into it.
const BUNDLED = new Set(['react', 'react-dom', 'scheduler', 'motion', 'framer-motion', 'motion-dom', 'motion-utils', 'ogl']);

const entries = [];
for (const [p, v] of Object.entries(lock)) {
  if (!p) continue;
  const name = p.replace(/^.*node_modules\//, '');
  if (v.dev && !BUNDLED.has(name)) continue;
  const dir = path.join(root, p);
  let pkg = {};
  try { pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8')); } catch { /* not installed */ }
  let licence = v.license || pkg.license || (pkg.licenses && pkg.licenses.map((l) => l.type).join(' OR ')) || 'not stated in the package';
  if (typeof licence === 'object') licence = licence.type;
  let text = '';
  try {
    const file = fs.readdirSync(dir).find((f) => /^(licen[sc]e|copying)(\.|$)/i.test(f));
    if (file) text = fs.readFileSync(path.join(dir, file), 'utf8').trim();
  } catch { /* not installed */ }
  const author = String(typeof pkg.author === 'string' ? pkg.author : (pkg.author && pkg.author.name) || '').replace(/\s*[<(].*$/, '');
  entries.push({ name, version: v.version, licence, text, author });
}
entries.sort((a, b) => a.name.localeCompare(b.name));

const out = [
  'Rift uses the open-source packages below. Each is used under its own licence, reproduced here.',
  'Where a package offers a choice of licences, Rift uses the permissive one (for example MIT).',
  'Generated by scripts/third-party-notices.js.',
  '',
];
for (const e of entries) {
  out.push('='.repeat(78), `${e.name} ${e.version}  (${e.licence})`, '='.repeat(78),
    e.text || (/^not stated/.test(e.licence)
      ? `This package does not state a licence (author: ${e.author || 'unknown'}). It is a small helper pulled in by another package.`
      : `This package doesn't ship its licence text. Author: ${e.author || 'see its repository'}. The standard terms of the ${e.licence} licence apply.`), '');
}
fs.writeFileSync(path.join(root, 'public', 'third-party-notices.txt'), out.join('\n'));
console.log(`Wrote ${entries.length} packages to public/third-party-notices.txt`);
